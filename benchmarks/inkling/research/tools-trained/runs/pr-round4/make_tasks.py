"""Rebuild each pr-live run's generated test requests as a task file, from its saved traces.

The test split cannot be regenerated byte for byte (the sampled answers differ between runs), but
the requests and expected command names the adapter and native arms saw are in their traces.
Follow-up rows ask for a second command only after a later user turn that the evaluator never
sends, so their expectation is cut to the first command (AMENDMENT-4, M2 in REVIEW-tools-pr.md).
The five follow-up ids come from the review and match the manifest's follow_tool count in both runs.

    python make_tasks.py
"""

import glob
import json
from pathlib import Path

HERE = Path(__file__).parent
LIVE = HERE.parent / "pr-live"


FOLLOW_IDS = {"test-00037", "test-00147", "test-00204", "test-00298", "test-00360"}  # follow_tool rows


def tasks(run: str) -> list[dict]:
    path = glob.glob(str(LIVE / run / "comparison" / "test_tools-adapter-*.jsonl"))[0]
    rows = []
    for line in Path(path).read_text().splitlines():
        r = json.loads(line)
        request = next(m["content"] for m in r["messages"] if m["role"] == "user")
        expected = r["expected"][:1] if r["id"] in FOLLOW_IDS else r["expected"]
        rows.append({"id": r["id"], "request": request, "commands": expected})
    return rows


if __name__ == "__main__":
    for run in ("final", "first-run"):
        manifest = json.loads((LIVE / run / "data" / "manifest.json").read_text())
        assert manifest["kinds"]["test"]["follow_tool"] == len(FOLLOW_IDS)
        rows = tasks(run)
        out = HERE / f"tasks-{run}.jsonl"
        out.write_text("".join(json.dumps(r) + "\n" for r in rows))
        print(run, len(rows), out)
        for r in rows:
            if r["id"] in FOLLOW_IDS:
                print("  ", r["id"], r["commands"], r["request"])
